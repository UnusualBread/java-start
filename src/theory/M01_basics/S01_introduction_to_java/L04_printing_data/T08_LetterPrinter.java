package theory.M01_basics.S01_introduction_to_java.L04_printing_data;

/*
Write a program that prints the following magic letter using * and whitespaces.
*/

public class T08_LetterPrinter {
    public static void main(String[] args) {
        System.out.println("*******");
        System.out.println("     **");
        System.out.println("     **");
        System.out.println("**   **");
        System.out.println("**   **");
        System.out.println(" ******");
    }
}
