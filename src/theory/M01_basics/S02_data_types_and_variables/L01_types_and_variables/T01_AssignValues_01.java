package theory.M01_basics.S02_data_types_and_variables.L01_types_and_variables;
/*
Given four variables. Assign values to these variables.
The variable one should be 1, two should be 2,
three should be 3 and four should be 4.
*/
public class T01_AssignValues_01 {
    public static void main(String[] args) {
        int one = 1;
        int two = 2;
        int three = 3;
        int four = 4;

        System.out.println(one + " " + two + " " + three + " " + four);    }
}
